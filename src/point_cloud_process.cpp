PointCloud::Ptr ConvertTriangulationResultToPointCloud(
    const TriangulationResult& triangulation_result)
{
  if (triangulation_result.points_3d.empty() || triangulation_result.valid_mask.empty())
  {
    throw std::invalid_argument("Triangulation result must not be empty.");
  }

  if (triangulation_result.points_3d.size() != triangulation_result.valid_mask.size())
  {
    throw std::invalid_argument("3D points and valid mask sizes must match.");
  }

  if (triangulation_result.points_3d.type() != CV_64FC3)
  {
    throw std::invalid_argument("Triangulation points must be CV_64FC3.");
  }

  if (triangulation_result.valid_mask.type() != CV_8UC1)
  {
    throw std::invalid_argument("Triangulation valid mask must be CV_8UC1.");
  }

  PointCloud::Ptr cloud(new PointCloud);

  cloud->reserve(triangulation_result.point_count);

  for (int y = 0; y < triangulation_result.points_3d.rows; ++y)
  {
    for (int x = 0; x < triangulation_result.points_3d.cols; ++x)
    {
      if (triangulation_result.valid_mask.at<unsigned char>(y, x) == 0)
      {
        continue;
      }

      const cv::Vec3d point = triangulation_result.points_3d.at<cv::Vec3d>(y, x);

      if (!std::isfinite(point[0]) || !std::isfinite(point[1]) || !std::isfinite(point[2]))
      {
        continue;
      }

      cloud->emplace_back(static_cast<float>(point[0]), static_cast<float>(point[1]),
                          static_cast<float>(point[2]));
    }
  }

  cloud->width = static_cast<std::uint32_t>(cloud->size());

  cloud->height = 1;

  cloud->is_dense = true;

  return cloud;
}

PointCloud::Ptr LoadPointCloud(const std::string& file_path)
{
  const std::string extension = GetLowerExtension(file_path);

  PointCloud::Ptr cloud(new PointCloud);

  int status = -1;

  if (extension == ".ply")
  {
    status = pcl::io::loadPLYFile<pcl::PointXYZ>(file_path, *cloud);
  }
  else if (extension == ".pcd")
  {
    status = pcl::io::loadPCDFile<pcl::PointXYZ>(file_path, *cloud);
  }
  else
  {
    throw std::invalid_argument("Point cloud input must be .ply or .pcd.");
  }

  if (status < 0)
  {
    throw std::runtime_error("Failed to load point cloud: " + file_path);
  }

  return cloud;
}

void SavePointCloud(const std::string& file_path, const PointCloud& cloud, bool binary)
{
  if (cloud.empty())
  {
    throw std::invalid_argument("Cannot save an empty point cloud.");
  }

  const std::string extension = GetLowerExtension(file_path);

  if (extension != ".ply" && extension != ".pcd")
  {
    throw std::invalid_argument("Point cloud output must use .ply or .pcd extension.");
  }

  EnsureParentDirectory(file_path);

  int status = -1;

  if (extension == ".ply")
  {
    status = binary ? SavePlyBinary(file_path, cloud) : SavePlyAscii(file_path, cloud);
  }
  else
  {
    status = binary ? pcl::io::savePCDFileBinary(file_path, cloud)
                    : pcl::io::savePCDFileASCII(file_path, cloud);
  }

  if (status < 0)
  {
    throw std::runtime_error("Failed to save point cloud: " + file_path);
  }
}

PointCloudProcessingResult ProcessPointCloud(const PointCloud& input_cloud,
                                             const PointCloudProcessingOptions& options)
{
  ValidateProcessingOptions(options);

  if (input_cloud.empty())
  {
    throw std::invalid_argument("Input point cloud must not be empty.");
  }

  PointCloudProcessingResult result;

  result.input_points = input_cloud.size();

  PointCloud::Ptr current(new PointCloud);

  std::vector<int> valid_indices;

  pcl::removeNaNFromPointCloud(input_cloud, *current, valid_indices);

  result.after_remove_nan = current->size();

  result.after_pass_through = current->size();

  if (options.pass_through.enabled)
  {
    pcl::PassThrough<pcl::PointXYZ> filter;

    filter.setInputCloud(current);

    filter.setFilterFieldName(options.pass_through.axis);

    filter.setFilterLimits(options.pass_through.min_limit, options.pass_through.max_limit);

    PointCloud::Ptr filtered(new PointCloud);

    filter.filter(*filtered);

    current = filtered;

    result.after_pass_through = current->size();
  }

  result.after_statistical_outlier = current->size();

  if (options.statistical_outlier.enabled && !current->empty())
  {
    if (current->size() <= static_cast<std::size_t>(options.statistical_outlier.mean_k))
    {
      throw std::runtime_error(
          "Point cloud is too small for configured StatisticalOutlier mean_k.");
    }

    pcl::StatisticalOutlierRemoval<pcl::PointXYZ> filter;

    filter.setInputCloud(current);

    filter.setMeanK(options.statistical_outlier.mean_k);

    filter.setStddevMulThresh(options.statistical_outlier.stddev_mul);

    PointCloud::Ptr filtered(new PointCloud);

    filter.filter(*filtered);

    current = filtered;

    result.after_statistical_outlier = current->size();
  }

  result.after_voxel_grid = current->size();

  if (options.voxel_grid.enabled && !current->empty())
  {
    pcl::VoxelGrid<pcl::PointXYZ> filter;

    filter.setInputCloud(current);

    filter.setLeafSize(options.voxel_grid.leaf_size, options.voxel_grid.leaf_size,
                       options.voxel_grid.leaf_size);

    PointCloud::Ptr filtered(new PointCloud);

    filter.filter(*filtered);

    current = filtered;

    result.after_voxel_grid = current->size();
  }

  result.cloud = current;

  return result;
}

