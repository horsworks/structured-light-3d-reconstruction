std::string GetLowerExtension(const std::string& file_path)
{
  std::string extension = std::filesystem::path(file_path).extension().string();

  std::transform(extension.begin(), extension.end(), extension.begin(), [](unsigned char character)
                 { return static_cast<char>(std::tolower(character)); });

  return extension;
}

void EnsureParentDirectory(const std::string& file_path)
{
  const std::filesystem::path path = file_path;

  if (!path.parent_path().empty())
  {
    std::filesystem::create_directories(path.parent_path());
  }
}

int SavePlyAscii(const std::string& file_path, const PointCloud& cloud)
{
  std::ofstream output(file_path);

  if (!output.is_open())
  {
    return -1;
  }

  output << "ply\n"
         << "format ascii 1.0\n"
         << "comment generated by structured-light-3d-reconstruction\n"
         << "element vertex " << cloud.size() << '\n'
         << "property float x\n"
         << "property float y\n"
         << "property float z\n"
         << "end_header\n";

  output << std::fixed << std::setprecision(7);

  for (const auto& point : cloud)
  {
    output << point.x << ' ' << point.y << ' ' << point.z << '\n';
  }

  return output.good() ? 0 : -1;
}

void WriteFloatLittleEndian(std::ostream& output, float value)
{
  static_assert(sizeof(float) == sizeof(std::uint32_t), "This PLY writer requires 32-bit float.");

  std::uint32_t bits = 0;

  std::memcpy(&bits, &value, sizeof(float));

  const unsigned char bytes[4] = {static_cast<unsigned char>(bits & 0xFFU),

                                  static_cast<unsigned char>((bits >> 8U) & 0xFFU),

                                  static_cast<unsigned char>((bits >> 16U) & 0xFFU),

                                  static_cast<unsigned char>((bits >> 24U) & 0xFFU)};

  output.write(reinterpret_cast<const char*>(bytes), sizeof(bytes));
}

int SavePlyBinary(const std::string& file_path, const PointCloud& cloud)
{
  std::ofstream output(file_path, std::ios::binary);

  if (!output.is_open())
  {
    return -1;
  }

  output << "ply\n"
         << "format binary_little_endian 1.0\n"
         << "comment generated by structured-light-3d-reconstruction\n"
         << "element vertex " << cloud.size() << '\n'
         << "property float x\n"
         << "property float y\n"
         << "property float z\n"
         << "end_header\n";

  for (const auto& point : cloud)
  {
    WriteFloatLittleEndian(output, point.x);

    WriteFloatLittleEndian(output, point.y);

    WriteFloatLittleEndian(output, point.z);
  }

  return output.good() ? 0 : -1;
}

void ValidateProcessingOptions(const PointCloudProcessingOptions& options)
{
  if (options.pass_through.enabled)
  {
    if (options.pass_through.axis != "x" && options.pass_through.axis != "y" &&
        options.pass_through.axis != "z")
    {
      throw std::invalid_argument("PassThrough axis must be x, y, or z.");
    }

    if (!std::isfinite(options.pass_through.min_limit) ||
        !std::isfinite(options.pass_through.max_limit) ||
        options.pass_through.min_limit >= options.pass_through.max_limit)
    {
      throw std::invalid_argument("Invalid PassThrough limits.");
    }
  }

  if (options.statistical_outlier.enabled)
  {
    if (options.statistical_outlier.mean_k <= 0)
    {
      throw std::invalid_argument("StatisticalOutlier mean_k must be positive.");
    }

    if (!std::isfinite(options.statistical_outlier.stddev_mul) ||
        options.statistical_outlier.stddev_mul <= 0.0)
    {
      throw std::invalid_argument("StatisticalOutlier stddev_mul must be positive.");
    }
  }

  if (options.voxel_grid.enabled)
  {
    if (!std::isfinite(options.voxel_grid.leaf_size) || options.voxel_grid.leaf_size <= 0.0F)
    {
      throw std::invalid_argument("VoxelGrid leaf_size must be positive.");
    }
  }
}

